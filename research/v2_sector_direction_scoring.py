"""Research-only two-sided sector direction evaluation with abstentions.

Signal rows MUST be generated by an independent as-of price module.
Outcomes cannot be consulted before the signal timestamp. No broker imports.
"""
from __future__ import annotations
from dataclasses import dataclass
from datetime import datetime
from math import sqrt

@dataclass(frozen=True)
class DirectionObservation:
    sector: str
    day: str
    signal_at: datetime
    latest_completed_bar_end: datetime
    predicted: str
    sector_prior_close: float
    sector_final_close: float

    def __post_init__(self):
        if self.predicted not in ("UP", "DOWN", "ABSTAIN"):
            raise ValueError("invalid forecast")
        if self.signal_at.tzinfo is None or self.latest_completed_bar_end.tzinfo is None:
            raise ValueError("timezone-aware datetimes required")
        if self.latest_completed_bar_end > self.signal_at:
            raise ValueError("future candle in forecast")
        if self.sector_prior_close <= 0 or self.sector_final_close <= 0:
            raise ValueError("invalid prices")

    @property
    def actual(self):
        return ("UP" if self.sector_final_close > self.sector_prior_close
                else "DOWN" if self.sector_final_close < self.sector_prior_close
                else "NEUTRAL")

def wilson_lower(successes: int, attempts: int, z: float = 1.96) -> float:
    if not 0 <= successes <= attempts:
        raise ValueError("bad counts")
    if not attempts:
        return 0.
    p = successes / attempts
    q = z * z
    return ((p + q/(2*attempts) - z*sqrt(p*(1-p)/attempts + q/(4*attempts*attempts)))
            / (1 + q/attempts))

def evaluate(observations: list[DirectionObservation]) -> dict:
    if len({(o.sector, o.day, o.signal_at) for o in observations}) != len(observations):
        raise ValueError("multiple forecasts per sector-day-time")
    valid = [o for o in observations if o.actual != "NEUTRAL"]
    emitted = [o for o in valid if o.predicted != "ABSTAIN"]
    correct = sum(o.actual == o.predicted for o in emitted)
    def side_metrics(side: str):
        rows = [o for o in emitted if o.predicted == side]
        wins = sum(o.actual == side for o in rows)
        return {"issued": len(rows), "correct": wins,
                "precision": wins/len(rows) if rows else None,
                "wilson_lower_95": wilson_lower(wins, len(rows))}
    return {"days": len(valid), "issued": len(emitted),
            "abstentions": len(valid)-len(emitted),
            "coverage":len(emitted)/len(valid) if valid else 0.,
            "correct":correct,
            "accuracy": correct/len(emitted) if emitted else None,
            "wilson_lower_95":wilson_lower(correct,len(emitted)),
            "up":side_metrics("UP"),"down":side_metrics("DOWN")}
