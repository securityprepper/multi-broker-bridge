"""Research-only regression: Decimal as R1M extension is not SQLite-bindable.

Runs entirely in an in-memory SQLite database. Never calls a broker or
writes production services/state. A fix should serialize Decimal to a finite
native numeric value before calling dp.save_signal, *not* loosen extension guards.
"""
import datetime as dt
import math
import sqlite3
import sys
import unittest
from decimal import Decimal
from pathlib import Path

HOST_MODULE = Path("/opt/securityprepper/direction-paper-executor")
sys.path[:0] = [str(HOST_MODULE),
    "/opt/securityprepper/quality-opportunity-watch",
    "/opt/securityprepper/owned-overnight-direction",
    "/opt/securityprepper/recent-owned-alerts",
    "/opt/securityprepper/multi-broker-bridge",
    "/opt/securityprepper/recommendation-paper-bridge",
    "/opt/securityprepper/sector-monitor"]
import direction_paper as dp

NOW = dt.datetime(2026, 11, 16, 18, 40, tzinfo=dt.timezone.utc)

def candidate():
    sig = dp.make_signal("R1M", "research-only-db-bind-repro",
                         "AMD", "UP", "R1M_PIVOT_UP", NOW,
                         price=466.7, momentum=0.3)
    # Exact value type generated by the deployed executor line.
    sig["vs_close_pct"] = round(
        (Decimal(str(sig["price"])) / Decimal("450.00") - 1) * 100, 4)
    return sig

class DecimalBindingRegression(unittest.TestCase):
    def setUp(self):
        self.db = sqlite3.connect(":memory:")
        self.db.executescript(dp.SCHEMA)

    def tearDown(self):
        self.db.close()

    def test_production_value_is_decimal(self):
        self.assertIsInstance(candidate()["vs_close_pct"], Decimal)

    def test_current_binding_fails_before_broker_access(self):
        sig = candidate()
        with self.assertRaisesRegex(sqlite3.ProgrammingError, "binding parameter 10"):
            dp.save_signal(self.db, sig, NOW)
        self.assertEqual(self.db.execute("SELECT count(*) FROM signals").fetchone()[0], 0)

    def test_safe_native_float_binding_only(self):
        sig = candidate()
        sig["vs_close_pct"] = float(sig["vs_close_pct"])
        self.assertTrue(math.isfinite(sig["vs_close_pct"]))
        self.assertTrue(dp.save_signal(self.db, sig, NOW))
        row = self.db.execute("SELECT vs_close_pct,source FROM signals").fetchone()
        self.assertEqual(row[1], "R1M")
        self.assertAlmostEqual(row[0], sig["vs_close_pct"], places=4)

if __name__ == "__main__":
    unittest.main(verbosity=2)
